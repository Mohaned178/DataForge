import { resolve } from 'node:path';
import { parseArgs } from 'node:util';
import {
  CanonicalLogViolationError,
  ECOMMERCE_RULES,
  ENGINE_VERSION,
  EventLogParseError,
  ScenarioValidationError,
  parseEventLog,
  parseScenario,
  replayCanonicalLog,
  serializeEventLog,
  serializeExpectedState,
  sha256Hex,
  simulate,
  type CanonicalEvent,
} from '@dataforge/core';
import { EXIT_FAILED, EXIT_OK, UsageError, formatCount, padRight, type CliIo } from '../cli-io';
import { CHECKSUMMED_FILES, RUN_FILES, readManifest, readRunFile, type RunManifest } from '../run-directory';

export const VERIFY_USAGE = 'dataforge verify --run <directory>';

type CheckStatus = 'OK' | 'FAIL' | 'SKIP';

class CheckReport {
  private failed = false;

  constructor(private readonly io: CliIo) {}

  record(step: string, subject: string, status: CheckStatus, details: readonly string[] = []): void {
    if (status === 'FAIL') {
      this.failed = true;
    }
    this.io.out(`  ${padRight(step, 10)} ${padRight(subject, 52)} ${status}`);
    for (const line of details) {
      this.io.out(`               ${line}`);
    }
  }

  get passed(): boolean {
    return !this.failed;
  }
}

/**
 * Independently re-derives everything a run directory claims:
 *   1. every file matches the checksum in manifest.json,
 *   2. events.jsonl parses against the event schema,
 *   3. replaying it satisfies log integrity and every business rule,
 *   4. the replayed state is byte-identical to expected-state.json,
 *   5. regenerating from scenario.resolved.json + seed reproduces the same events.
 */
export function runVerify(args: readonly string[], io: CliIo): number {
  const { values } = parseArgs({
    args: [...args],
    options: { run: { type: 'string' } },
    strict: true,
    allowPositionals: false,
  });
  if (values.run === undefined) {
    throw new UsageError(`Missing required option --run.\nUsage: ${VERIFY_USAGE}`);
  }
  const directory = resolve(values.run);
  const manifest = readManifest(directory);
  const report = new CheckReport(io);

  io.out(`DataForge verify: ${directory}`);
  io.out(`  generated by engine ${manifest.engineVersion}, seed ${manifest.seed}, scenario ${manifest.scenario.name}`);

  const files = new Map<string, string>();
  for (const name of CHECKSUMMED_FILES) {
    const content = readRunFile(directory, name);
    if (content === undefined) {
      report.record('checksum', name, 'FAIL', ['file is missing']);
      continue;
    }
    files.set(name, content);
    const actual = sha256Hex(content);
    const expected = manifest.files[name].sha256;
    report.record('checksum', name, actual === expected ? 'OK' : 'FAIL', actual === expected ? [] : [`manifest ${expected}`, `actual   ${actual}`]);
  }

  const eventLogText = files.get(RUN_FILES.events);
  const events = eventLogText === undefined ? undefined : parseEvents(eventLogText, report);
  if (events !== undefined) {
    replayAndCompare(events, files.get(RUN_FILES.expectedState), report);
  }
  regenerate(manifest, files.get(RUN_FILES.scenario), report);

  io.out(report.passed ? 'Result: PASS' : 'Result: FAIL');
  return report.passed ? EXIT_OK : EXIT_FAILED;
}

function parseEvents(text: string, report: CheckReport): CanonicalEvent[] | undefined {
  try {
    const events = parseEventLog(text);
    report.record('parse', `${formatCount(events.length)} events against event schema v1`, 'OK');
    return events;
  } catch (error) {
    if (error instanceof EventLogParseError) {
      report.record('parse', RUN_FILES.events, 'FAIL', [error.message]);
      return undefined;
    }
    throw error;
  }
}

function replayAndCompare(events: readonly CanonicalEvent[], expectedStateText: string | undefined, report: CheckReport): void {
  const subject = `${ECOMMERCE_RULES.length} business rules + 5 log integrity checks`;
  let replayedStateText: string;
  try {
    replayedStateText = serializeExpectedState(replayCanonicalLog(events).expectedState);
    report.record('replay', subject, 'OK');
  } catch (error) {
    if (error instanceof CanonicalLogViolationError) {
      report.record('replay', subject, 'FAIL', error.message.split('\n'));
      report.record('state', `replayed state vs ${RUN_FILES.expectedState}`, 'SKIP', ['replay did not complete']);
      return;
    }
    throw error;
  }
  if (expectedStateText === undefined) {
    report.record('state', `replayed state vs ${RUN_FILES.expectedState}`, 'SKIP', ['file is missing']);
    return;
  }
  const mismatch = firstDifferentLine(replayedStateText, expectedStateText);
  report.record(
    'state',
    `replayed state vs ${RUN_FILES.expectedState}`,
    mismatch === undefined ? 'OK' : 'FAIL',
    mismatch === undefined ? [] : [`first difference at line ${mismatch.line}:`, `  replayed: ${mismatch.replayed}`, `  file:     ${mismatch.file}`],
  );
}

function regenerate(manifest: RunManifest, scenarioText: string | undefined, report: CheckReport): void {
  const subject = 'regenerate from scenario + seed';
  if (manifest.engineVersion !== ENGINE_VERSION) {
    report.record('reproduce', subject, 'SKIP', [`run was made by engine ${manifest.engineVersion}; this is ${ENGINE_VERSION}`]);
    return;
  }
  if (scenarioText === undefined) {
    report.record('reproduce', subject, 'SKIP', [`${RUN_FILES.scenario} is missing`]);
    return;
  }
  try {
    const scenario = parseScenario(JSON.parse(scenarioText));
    const regenerated = sha256Hex(serializeEventLog(simulate({ scenario, seed: manifest.seed }).events));
    const expected = manifest.files[RUN_FILES.events].sha256;
    report.record('reproduce', subject, regenerated === expected ? 'OK' : 'FAIL', regenerated === expected ? [] : [`manifest   ${expected}`, `regenerated ${regenerated}`]);
  } catch (error) {
    if (error instanceof SyntaxError || error instanceof ScenarioValidationError) {
      report.record('reproduce', subject, 'FAIL', [`${RUN_FILES.scenario} is unusable: ${error.message.split('\n')[0] ?? ''}`]);
      return;
    }
    throw error;
  }
}

function firstDifferentLine(a: string, b: string): { line: number; replayed: string; file: string } | undefined {
  if (a === b) {
    return undefined;
  }
  const left = a.split('\n');
  const right = b.split('\n');
  const length = Math.max(left.length, right.length);
  for (let index = 0; index < length; index++) {
    if (left[index] !== right[index]) {
      return { line: index + 1, replayed: (left[index] ?? '<end of file>').trim(), file: (right[index] ?? '<end of file>').trim() };
    }
  }
  return { line: length, replayed: '<line endings differ>', file: '<line endings differ>' };
}
