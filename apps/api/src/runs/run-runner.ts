import { ENGINE_VERSION } from '@dataforge/core';
import { SerialQueue } from '../background/serial-queue';
import { generateRun, type GeneratedRun, type RunGenerator, type RunInputs } from './run-generation';

/** A run the runner has moved from queued to running; nobody else will process it. */
export interface ClaimedRun extends RunInputs {
  readonly id: string;
  readonly engineVersion: string;
}

/** Where run status and results live (the database, PrismaRunStore). */
export interface RunStore {
  /** Moves a queued run to running and returns it, or undefined when it is not queued (anymore). */
  claim(runId: string): Promise<ClaimedRun | undefined>;
  /** Stores the run's events, expected-state snapshot and manifest and marks it succeeded, atomically. */
  complete(runId: string, generated: GeneratedRun): Promise<void>;
  fail(runId: string, error: string): Promise<void>;
  /** Puts runs left running by a stopped process back in the queue and returns every queued run, oldest first. */
  requeueUnfinished(): Promise<string[]>;
}

export interface RunLog {
  log(message: string): void;
  error(message: string): void;
}

export interface RunRunnerOptions {
  readonly generate?: RunGenerator;
  readonly engineVersion?: string;
  readonly log?: RunLog;
}

const silent: RunLog = { log: () => undefined, error: () => undefined };

/**
 * Processes simulation runs in the background, one at a time, in the API process (ADR-0011). The
 * status lives in the database; this class only holds the order of the work it was given. Nest calls
 * onApplicationBootstrap (recovery) after start-up and onModuleDestroy (finish the current run)
 * before the database client disconnects.
 */
export class RunRunner {
  private readonly queue = new SerialQueue((runId) => this.process(runId));
  private readonly generate: RunGenerator;
  private readonly engineVersion: string;
  private readonly log: RunLog;

  constructor(
    private readonly store: RunStore,
    options: RunRunnerOptions = {},
  ) {
    this.generate = options.generate ?? generateRun;
    this.engineVersion = options.engineVersion ?? ENGINE_VERSION;
    this.log = options.log ?? silent;
  }

  enqueue(runId: string): void {
    this.queue.enqueue(runId);
  }

  /** Requeues the runs a stopped process left unfinished. Generation is deterministic, so the result is the same. */
  async recover(): Promise<number> {
    const unfinished = await this.store.requeueUnfinished();
    if (unfinished.length > 0) {
      this.log.log(`Resuming ${unfinished.length} unfinished run(s): ${unfinished.join(', ')}`);
    }
    unfinished.forEach((runId) => this.enqueue(runId));
    return unfinished.length;
  }

  /** Resolves when the queue is empty and no run is being processed. */
  whenIdle(): Promise<void> {
    return this.queue.whenIdle();
  }

  /** Takes no new work and waits for the run in progress; queued runs stay queued in the database. */
  stop(): Promise<void> {
    return this.queue.stop();
  }

  async onApplicationBootstrap(): Promise<void> {
    await this.recover();
  }

  async onModuleDestroy(): Promise<void> {
    await this.stop();
  }

  private async process(runId: string): Promise<void> {
    let claimed: ClaimedRun | undefined;
    try {
      claimed = await this.store.claim(runId);
    } catch (error) {
      this.log.error(`Run ${runId} could not be claimed and stays queued: ${messageOf(error)}`);
      return;
    }
    if (claimed === undefined) {
      return;
    }
    const startedAt = performance.now();
    let generated: GeneratedRun;
    try {
      if (claimed.engineVersion !== this.engineVersion) {
        throw new Error(
          `the run was requested for engine ${claimed.engineVersion}, but this API runs engine ${this.engineVersion}; ` +
            'a run is only generated by the engine it names, so that its output is reproducible',
        );
      }
      generated = this.generate(claimed);
    } catch (error) {
      await this.markFailed(runId, `Generation failed: ${messageOf(error)}`);
      return;
    }
    try {
      await this.store.complete(runId, generated);
    } catch (error) {
      await this.markFailed(runId, `Storing the run failed: ${messageOf(error)}`);
      return;
    }
    const elapsedMs = Math.round(performance.now() - startedAt);
    this.log.log(`Run ${runId} succeeded: ${generated.result.events.length} events in ${elapsedMs} ms`);
  }

  private async markFailed(runId: string, message: string): Promise<void> {
    this.log.error(`Run ${runId} failed. ${message}`);
    try {
      await this.store.fail(runId, message);
    } catch (error) {
      this.log.error(`Run ${runId} could not be marked failed and stays running until the next start: ${messageOf(error)}`);
    }
  }
}

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}
